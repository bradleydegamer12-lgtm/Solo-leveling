export const EXERCISE_MAP = Object.fromEntries(EXERCISES.map((e) => [e.id, e]));

export const LEVEL_RANK = { beginner: 0, intermediate: 1, advanced: 2 };

export function getExercise(id) {
  return EXERCISE_MAP[id] || null;
}

export function exerciseMinutes(ex) {
  if (!ex) return 0;
  const setSeconds = ex.seconds
    ? ex.seconds
    : (ex.reps || 8) * (ex.cat === "endurance" ? 3 : 4);
  const total = ex.sets * (setSeconds + (ex.rest || 30));
  return Math.max(1, Math.round(total / 60));
}
